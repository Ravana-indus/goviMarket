const STEPS = ["booked", "loaded", "in_transit", "arrived", "delivered"];
function shipSteps(x, kind) {
  const at = STEPS.indexOf(x.status);
  return `<div class="track">${STEPS.map((st, i) => `<span class="${i <= at ? "on" : ""}">${t("s_" + st)}</span>`).join("")}</div>
    ${x.ref ? `<div class="ship"><span>${t("ref")} <b>${esc(x.ref)}</b> · ${kind === "listing"
      ? `${t("dropoff")}: ${esc(x.lane.pickup || x.origin)}`
      : `${t("eta")}: ${new Date(x.schedule.delivered).toLocaleString("en-GB", { weekday: "short", hour: "2-digit", minute: "2-digit" })}`}</span></div>` : ""}`;
}
async function loadTrack() {
  $("t-signin").hidden = !!account;
  if (!account) { $("mine").innerHTML = ""; return; }
  $("mine").dataset.loaded = "1";
  const r = await fetch("/api/track");
  if (r.status === 401) { account = null; renderAccount(); return loadTrack(); }
  const d = await r.json();
  const card = (x, kind) => {
    const matched = x.matched_kg > 0;
    const ships = x.matches.map((m) => `${m.shipment ? shipSteps(m.shipment, kind) : ""}<div class="ship"><span>${m.lane ? MODE[m.lane.mode] || "🚚" : "📍"} <b>${Math.round(m.qty_kg)} kg</b> ${kind === "listing" ? t("to") + " " + esc(m.buyer) : t("from") + " " + esc(m.farmer)}
      ${m.lane ? `· ${esc(m.lane.origin)} ${m.lane.departs}` : ""}</span>
      <span>${kind === "listing" ? t("you_get") + " <b>" + rs(m.farmer_gets_lkr_per_kg) : "<b>" + rs(m.buyer_pays_lkr_per_kg)}${t("per_kg")}</b>
      ${kind === "listing" ? ` · ${t("transport_off")}: ${rs(m.transport_lkr_per_kg)}${t("per_kg")}${m.transport_lkr_per_kg < m.solo_transport_lkr_per_kg ? " · " + t("shared") : ""}` : ""}</span></div>`).join("");
    return `<div class="card item">
      <div class="row">${GOVI.icon(x.crop, 44)}<div><div class="title">${esc(cname(x.crop))} · ${Math.round(x.qty_kg)} kg</div>
        <div class="small muted">${kind === "listing" ? t("selling") : t("ordering")} · ${esc(x.location)} · ${day(x.ready_on || x.needed_by)}</div></div>
        <span class="chip ${matched ? "farmer" : "reporter"}">${matched ? t("matched") : t("waiting")}</span></div>
      ${ships}</div>`;
  };
  const html = d.listings.map((x) => card(x, "listing")).join("") + d.orders.map((x) => card(x, "order")).join("");
  $("mine").innerHTML = html || `<div class="card empty">${t("none")}</div>`;
}
